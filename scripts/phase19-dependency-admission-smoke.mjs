import { readFileSync } from 'node:fs';
import { evaluateDependencyPolicy } from '../packages/dependency-policy/src/index.ts';

let assertions = 0;
const ok = (value, message) => { assertions += 1; if (!value) throw new Error(message); };
const text = (path) => readFileSync(path, 'utf8');
const packageJson = JSON.parse(text('package.json'));
const dependencySource = text('packages/dependency-policy/src/index.ts');
const bootstrap = text('scripts/bootstrap-dependency-lock.mjs');
const workflow = text('.github/workflows/dependency-bootstrap.yml');
const workflowPolicy = JSON.parse(text('config/github-actions-policy.json'));
const ci = text('.github/workflows/ci.yml');
const releaseTruth = text('packages/release-truth/src/index.ts');
const dashboard = text('apps/dashboard/src/components/ReleaseTruthConsole.tsx');
const registry = text('FEATURE_REGISTRY.md');
const docker = text('Dockerfile');
const render = text('render.yaml');
const report = evaluateDependencyPolicy(process.cwd());

ok(packageJson.scripts['test:dependency-policy'], 'dependency contract script registered');
ok(packageJson.scripts['dependency:lock-policy'], 'dependency lock policy script registered');
ok(packageJson.scripts['dependency:bootstrap-lock'], 'lock bootstrap script registered');
ok(packageJson.scripts['release:dependency-lock-gate'], 'release-enforced lock gate registered');
ok(dependencySource.includes('EXACT_SEMVER'), 'exact direct dependency policy exists');
ok(dependencySource.includes("registry.npmjs.org"), 'trusted registry allowlist is explicit');
ok(dependencySource.includes('lockfileVersion !== 3'), 'npm v3 lockfile format is enforced');
ok(dependencySource.includes('lockfile.integrity_missing'), 'integrity digest absence blocks');
ok(dependencySource.includes('lockfile.registry_untrusted'), 'untrusted resolved origin blocks');
ok(dependencySource.includes('install_surface.unlocked'), 'post-lock npm-ci promotion is machine-enforced');
ok(bootstrap.includes("'--package-lock-only'"), 'bootstrap generates lock metadata only');
ok(bootstrap.includes("'--ignore-scripts'"), 'bootstrap does not run lifecycle scripts');
ok(bootstrap.includes("'--fetch-retries=0'"), 'bootstrap disables retry loops');
ok(bootstrap.includes("DEPENDENCY_BOOTSTRAP_TIMEOUT_MS") && bootstrap.includes("timeout: bootstrapTimeoutMs"), 'bootstrap network/process time is bounded and configurable');
ok(bootstrap.includes('rmSync(lockPath)'), 'failed bootstrap removes partial lock output');
ok(bootstrap.includes('packageBefore.equals(packageAfter)'), 'bootstrap blocks package.json mutation');
ok(bootstrap.includes('packageLockSha256'), 'bootstrap emits lock SHA-256 evidence');
ok(bootstrap.includes('lifecycleScriptsExecuted: false'), 'evidence records no lifecycle execution');
ok(bootstrap.includes('reviewRequiredBeforeCommitOrLifecycleExecution: true'), 'evidence records mandatory human review boundary');
ok(workflow.includes('workflow_dispatch'), 'lock bootstrap workflow is manual');
const uploadAction = workflowPolicy.actions['actions/upload-artifact'];
ok(workflow.includes(`actions/upload-artifact@${uploadAction.sha} # ${uploadAction.version}`), 'bootstrap uploads review artifact through the reviewed immutable action pin');
ok(!/\bnpm ci\b/.test(workflow.split('Review boundary')[0]), 'bootstrap workflow does not install/execute the generated graph');
ok(ci.includes('npm run release:dependency-lock-gate'), 'CI verify requires reviewed lock policy');
ok(ci.includes('npm ci --no-audit --no-fund'), 'CI verify installs only from committed lock');
ok(ci.includes('npm audit --audit-level=high'), 'CI dependency-backed verification includes advisory audit');
ok(ci.includes('npm run release:sbom'), 'CI dependency-backed verification emits SBOM');
ok(releaseTruth.includes('evaluateDependencyPolicy'), 'release truth consumes dependency policy');
ok(dashboard.includes('นโยบายแหล่งแพ็กเกจ'), 'Dashboard surfaces dependency admission evidence');
ok(registry.includes('| QA-003 | Full dependency-backed typecheck/test/build | BLOCKED |'), 'QA-003 remains honestly blocked');
ok(/npm install/.test(docker) && /npm install/.test(render), 'deployment install promotion is intentionally deferred until reviewed lock exists');
ok(report.sourcePolicyReady, 'current exact direct dependency source policy passes');
ok(!report.lockfilePresent && !report.ready, 'current missing lock remains blocked');
ok(report.findings.length === 1 && report.findings[0].code === 'lockfile.missing', 'current dependency blocker remains singular and explicit');
ok(report.installSurfaces.some((item) => item.name === 'ci.verify' && item.mode === 'npm-ci'), 'CI install surface already uses npm ci');
ok(report.installSurfaces.filter((item) => item.mode === 'npm-install').length === 2, 'Docker and Render remain staged for post-review npm-ci promotion');

console.log(`phase19-dependency-admission-smoke PASS · ${assertions} assertions`);
