import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createSteamNewsAdapter, BUILTIN_INTEGRATIONS } from '../packages/integrations/src/index.ts';
import { evaluateDurableDeploymentProfile } from '../packages/config/src/deployment-profile-pure.ts';
import { defaultSetupDraft, normalizeSetupDraft } from '../packages/control-center/src/index.ts';

let assertions=0; const check=(fn)=>{fn();assertions+=1;};
const fakeHttp={json:async(url)=>{check(()=>assert.match(url,/^https:\/\/api\.steampowered\.com\/ISteamNews\/GetNewsForApp\/v2\//));return {appnews:{appid:570,count:1,newsitems:[{gid:'1',title:'Update',url:'https://store.steampowered.com/news/app/570/view/1',date:1786675200,contents:'Patch notes',feedlabel:'Community Announcements',feedname:'steam_community_announcements',feed_type:1,appid:570}]}};}};
const steam=createSteamNewsAdapter(fakeHttp);
check(()=>assert.equal(steam.key,'steam-news'));
check(()=>assert.deepEqual(steam.config?.validate({appId:570,count:10,maxLength:1200}),{appId:570,count:10,maxLength:1200}));
check(()=>assert.throws(()=>steam.config?.validate({appId:'nope'}),/STEAM_NEWS_APP_ID_INVALID/));
const result=await steam.sync?.({config:{appId:570,count:10,maxLength:1200}});
check(()=>assert.equal(result?.contentType,'steam-news'));
check(()=>assert.equal(result?.itemCount,1));
check(()=>assert.equal(result?.payload.provider,'steam-news'));
check(()=>assert.ok(BUILTIN_INTEGRATIONS.some((item)=>item.key==='steam-news'&&item.capabilities.news)));
const base=defaultSetupDraft();
check(()=>assert.equal(base.integrations.steamNews.enabled,false));
const normalized=normalizeSetupDraft({...base,integrations:{...base.integrations,steamNews:{enabled:true,appId:570,count:20,maxLength:2000,syncCadence:'DAILY'}}});
check(()=>assert.deepEqual(normalized.integrations.steamNews,{enabled:true,appId:570,count:20,maxLength:2000,syncCadence:'DAILY'}));
const supabase=evaluateDurableDeploymentProfile({DATABASE_URL:'postgresql://u:p@db.example.supabase.co:5432/postgres',SUPABASE_URL:'https://example.supabase.co',SUPABASE_SECRET_KEY:'redacted',SUPABASE_STORAGE_BUCKET:'autoserver-assets'});
check(()=>assert.equal(supabase.database.providerHint,'supabase'));
check(()=>assert.equal(supabase.assetStorage.provider,'supabase'));
check(()=>assert.equal(supabase.assetStorage.keyType,'secret'));
check(()=>assert.deepEqual(supabase.incomplete,[]));
const partial=evaluateDurableDeploymentProfile({SUPABASE_URL:'https://example.supabase.co'});
check(()=>assert.ok(partial.incomplete.includes('SUPABASE_SERVER_KEY_REQUIRED_FOR_STORAGE')));
check(()=>assert.ok(partial.incomplete.includes('DATABASE_URL_REQUIRED_FOR_DURABLE_STATE')));
const legacy=evaluateDurableDeploymentProfile({DATABASE_URL:'postgresql://localhost/db',SUPABASE_URL:'https://example.supabase.co',SUPABASE_SERVICE_ROLE_KEY:'legacy'});
check(()=>assert.equal(legacy.assetStorage.keyType,'legacy-service-role'));
const setupWorker=await readFile('apps/platform/src/runtime/setup-worker.ts','utf8');
check(()=>assert.match(setupWorker,/'steam-news':\{enabled:setupDraft\.integrations\.steamNews\.enabled/));
const discordSetup=await readFile('apps/platform/src/discord/setup.ts','utf8');
check(()=>assert.match(discordSetup,/setCustomId\('steam_news'\)/));
const dashboard=await readFile('apps/dashboard/src/App.tsx','utf8');
check(()=>assert.match(dashboard,/ข่าว Steam/));
const httpServer=await readFile('apps/platform/src/http/server.ts','utf8');
check(()=>assert.match(httpServer,/durable: evaluateDurableDeploymentProfile\(deps\.config\)/));
console.log(`[phase17-completion] PASS ${assertions} assertions`);
